import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "assets", "bookmark.png");
const OUT = join(ROOT, "src", "bookmark-art.ts");

const png = readFileSync(SRC);
const width = png.readUInt32BE(16);
const height = png.readUInt32BE(20);
// Committed because the publishing service builds src/index.ts with esbuild and runs no asset step.
const source =
    `// Generated by scripts/build-art.mjs from assets/bookmark.png. Do not edit by hand.\n` +
    `export const BOOKMARK_ART = ${JSON.stringify({
        uri: `data:image/png;base64,${png.toString("base64")}`,
        width,
        height,
    })};\n`;
if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== source)
    writeFileSync(OUT, source);
